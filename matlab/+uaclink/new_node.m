function node = new_node(name)
%NEW_NODE Volatile point-to-point stop-and-wait state, sequence starts at zero.
node=struct('name',char(name),'next_sequence',0,'expected_sequence',0, ...
    'last_delivered_sequence',-1,'last_delivered_payload',zeros(1,0,'uint8'), ...
    'delivered',{{}},'delivered_sequences',zeros(1,0), ...
    'state','idle','pending_sequence',NaN,'pending_payload',zeros(1,0,'uint8'), ...
    'attempts',0,'deadline_s',Inf,'last_event','initialized');
end
